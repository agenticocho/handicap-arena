#!/usr/bin/env python3
"""CROSSWORD CRATE -- our own puzzles, our own word list, no third-party content.

WHY GENERATED AND NOT INGESTED. The Guardian's terms forbid using their content "for any machine
learning ... purposes", "for any text and data aggregation, analysis or mining purposes", and creating "a
database ... comprising all or part of the material". A benchmark crate of their puzzles is all three, and
"freely readable" is not "freely shippable". So the crate is built from a word list declared in this file,
with clues generated by our own templates. Nothing outside this repo is read.

SHAPE. A criss-cross ("freeform") grid: every answer is a declared word, every word after the first crosses
at least one existing letter, and the placement rule guarantees no accidental run of letters. There is no
symmetry claim; the crate declares its construction instead of implying a style it does not have.

TWO GATES, in the arena's units:

  CEILING  is it solvable WITHOUT the crossings? `ceiling_anagram_only` sees only the clue's scrambled
           letters and the enumeration. If every slot resolves uniquely that way, the puzzle offers no grid
           work at all. Reported as a count, never as a pass: `anagram_resolved / slots`.

  FLOOR    can a real solver win it at all? `floor_crossing_solve` fills from the declared list using the
           crossings; its expanded-state count is the move count. `UNWINNABLE` is an exhausted frontier, and
           a bitten budget returns `UNDETERMINED` -- never a low score.

Every solution is replayed into the grid before it is printed.

    python3 crossword_gen.py --self-test
    python3 crossword_gen.py --puzzles 3 --seed 7 --out probes/CROSSWORD_CRATE_2026-11-05.json
"""
