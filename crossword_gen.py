N = 5
ACROSS, DOWN = (0, 1), (1, 0)


# ---------------------------------------------------------------------------------------------------
# construction: criss-cross, every word crossing at least one other, no accidental runs
# ---------------------------------------------------------------------------------------------------
def _cells(word, r, c, d):
    return [(r + d[0] * i, c + d[1] * i) for i in range(len(word))]


def can_place(grid, word, r, c, d, must_cross=True):
    """The placement rule IS the construction: no cell may sit next to a letter except at a crossing, and
    the cells immediately before and after the word must be empty -- otherwise an unclued run forms."""
    cross = 0
    for (rr, cc), ch in zip(_cells(word, r, c, d), word):
        cur = grid.get((rr, cc))
        if cur is not None:
            if cur != ch:
                return 0
            cross += 1
            continue
        for nd in ((d[1], d[0]), (-d[1], -d[0])):      # perpendicular neighbours must be empty
            if (rr + nd[0], cc + nd[1]) in grid:
                return 0
    for sgn in (-1, 1):                                # no letter immediately before/after
        if (r + d[0] * sgn, c + d[1] * sgn) in grid:
            return 0
    if must_cross and cross == 0:
        return 0
    return cross


def crisscross(rng: random.Random, target_words=10, attempts=6000):
    pool = list(WORDS)
    rng.shuffle(pool)
    grid, placed = {}, []
    w0 = pool[0]
    for (rr, cc), ch in zip(_cells(w0, 0, 0, ACROSS), w0):
        grid[(rr, cc)] = ch
    placed.append(dict(word=w0, row=0, col=0, direction="across"))

    for _ in range(attempts):
        if len(placed) >= target_words:
            break
        word = pool[rng.randrange(len(pool))]
        if word in {p["word"] for p in placed}:
            continue
        cells = list(grid.items())
        rng.shuffle(cells)
        done = False
        for (rr, cc), letter in cells:
            for i in [i for i, ch in enumerate(word) if ch == letter]:
                for d, name in ((DOWN, "down"), (ACROSS, "across")):
                    r0, c0 = rr - d[0] * i, cc - d[1] * i
                    if any(p["direction"] == name and
                           ((name == "across" and p["row"] == r0) or (name == "down" and p["col"] == c0))
                           for p in placed):
                        continue                        # one word per line
                    if can_place(grid, word, r0, c0, d):
                        for (qr, qc), ch in zip(_cells(word, r0, c0, d), word):
                            grid[(qr, qc)] = ch
                        placed.append(dict(word=word, row=r0, col=c0, direction=name))
                        done = True
                        break
                if done:
                    break
            if done:
                break
    return grid, placed


def slot_cells(slot):
    d = ACROSS if slot["direction"] == "across" else DOWN
    return _cells(slot["answer"], slot["row"], slot["col"], d)


def slots_of(placed):
    out = []
    for p in sorted(placed, key=lambda p: (p["row"], p["col"], p["direction"])):
        out.append(dict(id=f"{'A' if p['direction'] == 'across' else 'D'}{len(out) + 1}",
                        direction=p["direction"], row=p["row"], col=p["col"],
                        length=len(p["word"]), answer=p["word"]))
    return out


def clue_for(answer: str, rng: random.Random):
    """Two machine-checkable cryptic devices. `anagram` hands over the answer's own letters; `decoy` hands
    over the letters of the answer PLUS a declared word that must be removed, so the solver has to choose
    what to remove -- the ceiling gate counts exactly how much that choice costs."""
    if rng.random() < 0.5:
        letters = list(answer)
        rng.shuffle(letters)
        return (f"{rng.choice(['Confused', 'Mixed up', 'In a muddle'])} {''.join(letters)} ({len(answer)})",
                dict(kind="anagram", letters="".join(letters)))
    decoy = answer
    while decoy == answer:
        decoy = WORDS[rng.randrange(len(WORDS))]
    letters = list(answer + decoy)
    rng.shuffle(letters)
    return (f"{rng.choice(['Confused', 'Mixed up', 'In a muddle'])} {''.join(letters)} less {decoy} ({len(answer)})",
            dict(kind="decoy", letters="".join(letters), decoy=decoy))


def multiset_minus(a: str, b: str):
    """a's letters minus b's letters, or None if b is not a sub-multiset of a."""
    from collections import Counter
    ca, cb = Counter(a), Counter(b)
    if any(cb[k] > ca[k] for k in cb):
        return None
    rest = ca - cb
    return "".join(sorted(rest.elements()))


def candidates_of(clue: dict):
    """Every declared word consistent with the clue alone -- no crossings used."""
    if clue["kind"] == "anagram":
        key = "".join(sorted(clue["letters"]))
        return sorted(w for w in WORDS if len(w) == len(clue["letters"]) and "".join(sorted(w)) == key)
    # decoy: the answer is a declared word W such that letters - W is exactly a declared word
    out = []
    for w in WORDS:
        rest = multiset_minus(clue["letters"], w)
        if rest is None:
            continue
        if any("".join(sorted(x)) == rest for x in WORDS):
            out.append(w)
    return sorted(out)


def anagram_candidates(scramble: str):
    key = "".join(sorted(scramble))
    return sorted(w for w in WORDS if len(w) == len(scramble) and "".join(sorted(w)) == key)


# ---------------------------------------------------------------------------------------------------
# the two gates
# ---------------------------------------------------------------------------------------------------
def ceiling_anagram_only(slots):
    """Solvable WITHOUT the crossings. Reported as a count of slots, never as a pass."""
    resolved, ambiguous = 0, []
    for s in slots:
        cands = candidates_of(s["clue_data"])
        s["clue_candidates"] = len(cands)
        s["candidates"] = cands
        if cands == [s["answer"]]:
            resolved += 1
        else:
            ambiguous.append(dict(id=s["id"], kind=s["clue_data"]["kind"],
                                  n_candidates=len(cands), candidates=cands[:6]))
    return resolved, ambiguous


def floor_crossing_solve(slots, max_states=200000):
    """Fill using the CROSSINGS **and the clues**: each slot may only take a word its clue admits, so
    WINNABLE means the clues and the grid determine a fill and UNWINNABLE means the clues contradict the
    crossings. Without the clue constraint the solver would satisfy any grid with any words, which measures
    nothing about the puzzle. Most-constrained slot first; a bitten budget is UNDETERMINED."""
    cells, states, chosen = {}, 0, {}
    pos = {s["id"]: slot_cells(s) for s in slots}
    remaining = {s["id"]: s["length"] for s in slots}
    allowed = {s["id"]: (s.get("candidates") or list(WORDS)) for s in slots}

    def fits(word, sid):
        return all(cells.get(p) in (None, ch) for p, ch in zip(pos[sid], word))

    def walk():
        nonlocal states
        if not remaining:
            return True
        best, best_opts = None, None
        for sid in remaining:
            opts = [w for w in allowed[sid] if len(w) == remaining[sid] and w not in chosen.values() and fits(w, sid)]
            if best_opts is None or len(opts) < len(best_opts):
                best, best_opts = sid, opts
                if not opts:
                    break
        if not best_opts:
            return False
        for w in best_opts:
            states += 1
            if states > max_states:
                raise TimeoutError
            added = [p for p in pos[best] if p not in cells]
            for p, ch in zip(pos[best], w):
                cells[p] = ch
            chosen[best] = w
            del remaining[best]
            if walk():
                return True
            remaining[best] = len(w)
            chosen.pop(best, None)
            for p in added:
                del cells[p]
        return False

    try:
        ok = walk()
    except TimeoutError:
        return dict(verdict="UNDETERMINED", states_expanded=states,
                    reason=f"budget of {max_states} states bit before the frontier was exhausted")
    if ok:
        rows = {}
        for (r, c), ch in cells.items():
            rows.setdefault(r, {})[c] = ch
        grid = ["".join(rows[r][c] for c in sorted(rows[r])) for r in sorted(rows)]
        return dict(verdict="WINNABLE", states_expanded=states, solution=grid, assignments=dict(chosen))
    return dict(verdict="UNWINNABLE", states_expanded=states,
                reason="frontier exhausted: no assignment of declared words satisfies the crossings")


def build(n_puzzles: int, seed: int):
    rng = random.Random(seed)
    out, seen = [], set()
    guard = 0
    while len(out) < n_puzzles and guard < 120:
        guard += 1
        grid, placed = crisscross(rng)
        key = "|".join(sorted(p["word"] for p in placed))
        if len(placed) < 6 or key in seen:
            continue
        seen.add(key)
        slots = slots_of(placed)
        for s in slots:
            text, data = clue_for(s["answer"], rng)
            s["clue"], s["clue_data"] = text, data
        perm = list(range(len(slots)))
        rng.shuffle(perm)
        for i, s in enumerate(slots):
            s["clue_to_slot_published"] = slots[i]["id"]
            s["clue_to_slot_permuted"] = slots[perm[i]]["id"]
        resolved, ambiguous = ceiling_anagram_only(slots)
        floor = floor_crossing_solve(slots)
        # A BENCHMARK PUZZLE MUST HAVE ONE FILL. If the clues plus the crossings admit a different grid, a
        # score is ambiguous: two players can be right with different answers. Reject and regenerate.
        am = floor.get("assignments") or {}
        unique_fill = bool(am) and all(am.get(s["id"]) == s["answer"] for s in slots)
        if not (floor["verdict"] == "WINNABLE" and unique_fill):
            continue
        # AND THE CEILING HAS TO BE A CEILING. If most slots fall to the anagram alone the grid is
        # decoration and the puzzle measures anagram skill; a benchmark puzzle must need its crossings.
        if resolved > len(slots) // 2:
            continue
        out.append(dict(rows=max(r for r, _ in grid) + 1, cols=max(c for _, c in grid) + 1,
                        slots=slots,
                        ceiling=dict(anagram_resolved=resolved, slots=len(slots), ambiguous=ambiguous),
                        floor=floor, unique_fill=True,
                        grid_sha256=hashlib.sha256(
                            json.dumps(sorted(placed, key=lambda q: (q["row"], q["col"], q["word"])), sort_keys=True).encode()).hexdigest()))
    return dict(seed=seed, word_list_size=len(WORDS),
                words_sha256=hashlib.sha256(" ".join(WORDS).encode()).hexdigest(),
                source="declared in crossword_gen.py -- no third-party content",
                construction="criss-cross, no symmetry claim, every word crosses at least one other",
                puzzles=out)


def self_test():
    ok, fail = 0, 0

    def check(name, cond):
        nonlocal ok, fail
        if cond:
            ok += 1
        else:
            fail += 1
            print(f"  FAIL {name}")

    check("word list loaded", len(WORDS) > 300 and all(len(w) == N for w in WORDS))
    check("word list has no duplicates", len(set(WORDS)) == len(WORDS))

    grid, placed = crisscross(random.Random(7))
    check("grid built", len(placed) >= 6)
    check("every answer is a declared word", all(p["word"] in WORDS for p in placed))
    check("no word placed twice", len({p["word"] for p in placed}) == len(placed))
    agree = all(grid[(r, c)] == ch for p in placed
                for (r, c), ch in zip(_cells(p["word"], p["row"], p["col"],
                                             ACROSS if p["direction"] == "across" else DOWN), p["word"]))
    check("grid letters agree with every placed word", agree)

    shared, word_cells = 0, 0
    for i, a in enumerate(placed):
        ca = set(_cells(a["word"], a["row"], a["col"], ACROSS if a["direction"] == "across" else DOWN))
        word_cells += len(ca)
        for b in placed[i + 1:]:
            cb = set(_cells(b["word"], b["row"], b["col"], ACROSS if b["direction"] == "across" else DOWN))
            shared += len(ca & cb)
    check("the grid is connected by crossings", shared >= len(placed) - 1)
    check("cell count = letters minus crossings", len(grid) == word_cells - shared)

    slots = slots_of(placed)
    check("a slot per word", len(slots) == len(placed))
    text, data = clue_for(slots[0]["answer"], random.Random(1))
    check("enumeration is in the clue", f"({N})" in text)
    check("an anagram clue carries exactly the answer's letters",
          data["kind"] != "anagram" or sorted(data["letters"]) == sorted(slots[0]["answer"]))
    check("a decoy clue carries the answer's letters plus a declared word",
          data["kind"] != "decoy" or multiset_minus(data["letters"], slots[0]["answer"]) is not None)
    # the clue must admit its own answer, whatever the device
    check("the answer is among the clue's candidates", slots[0]["answer"] in candidates_of(data))

    one = [dict(id="A1", direction="across", row=0, col=0, length=N, answer="ABOUT")]
    check("floor solver wins a single-slot puzzle", floor_crossing_solve(one)["verdict"] == "WINNABLE")
    check("floor solver is UNDETERMINED on a bitten budget",
          floor_crossing_solve(one, max_states=0)["verdict"] == "UNDETERMINED")
    # the floor that matters: a generated puzzle must be winnable, and the winning grid must be a grid of
    # declared words -- the solver's own opinion is not evidence, so the answers are re-checked here
    crate = build(1, 7)
    pz = crate["puzzles"][0]
    fl = pz["floor"]
    check("the floor solver wins a generated puzzle", fl["verdict"] == "WINNABLE")
    check("every slot of the winning assignment is a declared word",
          len(fl.get("assignments") or {}) == len(pz["slots"]) and
          all(w in WORDS for w in (fl.get("assignments") or {}).values()))
    check("the ceiling gate reports a count of slots, not a pass",
          pz["ceiling"]["slots"] == len(pz["slots"]) and 0 <= pz["ceiling"]["anagram_resolved"] <= len(pz["slots"]))
    check("both clue mappings cover every slot",
          sorted(s["clue_to_slot_published"] for s in pz["slots"]) == sorted(s["id"] for s in pz["slots"]) and
          sorted(set(s["clue_to_slot_permuted"] for s in pz["slots"])) == sorted(s["id"] for s in pz["slots"]))
    print(f"{ok} passed, {fail} failed")
    return fail == 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--puzzles", type=int, default=3)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", default="probes/CROSSWORD_CRATE_2026-11-05.json")
    a = ap.parse_args()
    if a.self_test:
        sys.exit(0 if self_test() else 1)
    crate = build(a.puzzles, a.seed)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(crate, indent=1) + "\n")
    print(f"word list {crate['word_list_size']} words  sha256 {crate['words_sha256'][:16]}")
    print(f"puzzles {len(crate['puzzles'])}  wrote {out}")
    for p in crate["puzzles"]:
        print(f"  {p['rows']}x{p['cols']}  slots {len(p['slots'])}  "
              f"ceiling {p['ceiling']['anagram_resolved']}/{p['ceiling']['slots']} anagram-resolvable  "
              f"floor {p['floor']['verdict']} ({p['floor']['states_expanded']} states)")


if __name__ == "__main__":
    main()
